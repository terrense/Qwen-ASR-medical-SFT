MEDICAL_ENTITY_CATEGORIES = OrderedDict([
    ("imaging_exam", IMAGING_EXAMS),
    ("lab_test", LAB_TESTS),
    ("disease", DISEASES),
    ("medication", MEDICATIONS),
    ("department", DEPARTMENTS),
    ("symptom", SYMPTOMS),
    ("abbreviation", ABBREVIATIONS),
])


def build_entity_lexicon():
    """Terms grouped by category, deduplicated across categories.

    A term is assigned to the first category that claims it, in the order of
    ``MEDICAL_ENTITY_CATEGORIES``. Imaging and lab entries win over the broader
    abbreviation list so that "CT" is scored as an imaging exam and only
    genuinely abbreviation-only tokens land in that bucket.
    """
    assigned = {}
    result = OrderedDict()
    for category, terms in MEDICAL_ENTITY_CATEGORIES.items():
        bucket = []
        for term in terms:
            key = term.lower()
            if key in assigned:
                continue
            assigned[key] = category
            bucket.append(key)
        result[category] = sorted(set(bucket))
    return result


